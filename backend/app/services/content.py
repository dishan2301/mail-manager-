def _frontend_strings() -> set[str]:
    values: set[str] = set()
    if not FRONTEND_SRC.exists():
        return values
    for path in FRONTEND_SRC.rglob("*"):
        if path.suffix not in {".tsx", ".ts", ".css"}:
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        for jsx_text, literal in TEXT_RE.findall(text):
            value = html.unescape((jsx_text or literal).strip())
            if len(value) >= 2 and any(char.isalpha() for char in value):
                values.add(value)
    return values


def seed_ui_content(db: Session) -> int:
    existing_rows = {
        row.source_text: row
        for row in db.scalars(select(UIContent))
    }
    defaults = {**BACKEND_DEFAULTS, **FRONTEND_DEFAULTS}
    existing = set(existing_rows)
    pending: dict[str, str] = {value: value for value in sorted(_frontend_strings()) if value not in existing}
    pending.update({key: value for key, value in BACKEND_DEFAULTS.items() if key not in existing})
    pending.update({key: value for key, value in FRONTEND_DEFAULTS.items() if key not in existing})
    rows = [UIContent(source_text=key, rendered_text=value, active=True) for key, value in pending.items()]
    updated = 0
    for key, row in existing_rows.items():
        if row.rendered_text == key and key in defaults and defaults[key] != key:
            row.rendered_text = defaults[key]
            updated += 1
    pending_filter = existing_rows.get("filter.pending")
    if pending_filter and pending_filter.rendered_text == "Pending":
        pending_filter.rendered_text = FRONTEND_DEFAULTS["filter.pending"]
        updated = 1
    if not rows and not updated:
        return 0
    if rows:
        db.add_all(rows)
    db.commit()
    return len(rows) + updated


def content(db: Session, key: str, **values: object) -> str:
    row = db.scalar(select(UIContent).where(UIContent.source_text == key, UIContent.active.is_(True)))
    template = row.rendered_text if row else BACKEND_DEFAULTS.get(key, key)
    return template.format(**values) if values else template
